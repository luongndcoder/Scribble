//! Produce speaker-turn labels for a recording using Soniox realtime STT — the
//! reference the local live diarizer is measured against
//! (`examples/live_diar_eval.rs`).
//!
//! Runs the file through the SAME `run_soniox_session` the app uses, with the
//! API key from the app's Settings database (never printed). Each Soniox chunk
//! is one speaker run; its final version becomes one label line:
//!   `start_s end_s S<id>`
//!
//! Run:
//!   cargo run --release --example soniox_labels -- <16k-mono.wav> <out-labels.txt>
//! Env: `SONIOX_SPEED` (default 1.5x realtime; realtime Soniox cannot process much faster, a faster feed only queues audio server-side).
use std::collections::BTreeMap;
use std::time::{Duration, Instant};

use voicescribe_lib::stt::{run_soniox_session, SonioxConfig, SonioxSegment};

#[tokio::main(flavor = "multi_thread", worker_threads = 4)]
async fn main() {
    let args: Vec<String> = std::env::args().collect();
    let (Some(wav), Some(out)) = (args.get(1), args.get(2)) else {
        eprintln!("usage: soniox_labels <16k-mono.wav> <out-labels.txt>");
        std::process::exit(2);
    };
    let speed: f64 = std::env::var("SONIOX_SPEED").ok().and_then(|v| v.parse().ok()).unwrap_or(1.5);

    let db = voicescribe_lib::db::Database::init(None).expect("open settings db");
    let key = db
        .get_setting("soniox_api_key")
        .ok()
        .flatten()
        .filter(|k| !k.trim().is_empty())
        .or_else(|| std::env::var("SONIOX_API_KEY").ok())
        .expect("no Soniox API key in Settings or SONIOX_API_KEY");
    let mut cfg = SonioxConfig::new(key);
    if let Some(h) = db.get_setting("soniox_language_hints").ok().flatten() {
        let hints: Vec<String> = h.split([',', ' ']).map(str::trim).filter(|s| !s.is_empty()).map(String::from).collect();
        if !hints.is_empty() {
            cfg.language_hints = hints;
        }
    }

    let pcm = voicescribe_lib::stt::strip_wav_header(&std::fs::read(wav).expect("read wav"));
    let (audio_tx, audio_rx) = tokio::sync::mpsc::channel::<Option<Vec<u8>>>(500);
    let (seg_tx, mut seg_rx) = tokio::sync::mpsc::channel::<SonioxSegment>(1024);
    let session = tokio::spawn(run_soniox_session(cfg, audio_rx, seg_tx));

    const FRAME: usize = 1600 * 2; // 100 ms
    let frames = pcm.len() / FRAME;
    let feeder = tokio::spawn(async move {
        let t0 = Instant::now();
        for i in 0..frames {
            let due = Duration::from_secs_f64(i as f64 * 0.1 / speed);
            if let Some(w) = due.checked_sub(t0.elapsed()) {
                tokio::time::sleep(w).await;
            }
            if audio_tx.send(Some(pcm[i * FRAME..(i + 1) * FRAME].to_vec())).await.is_err() {
                return;
            }
            if i % 3000 == 0 {
                eprintln!("fed {:.0}s / {:.0}s", i as f64 * 0.1, frames as f64 * 0.1);
            }
        }
        let _ = audio_tx.send(None).await;
    });

    // chunk_id -> latest (start_ms, end_ms, speaker_id)
    let mut chunks: BTreeMap<String, (i64, i64, i64)> = BTreeMap::new();
    while let Some(seg) = seg_rx.recv().await {
        if seg.error == Some(true) {
            eprintln!("SONIOX ERROR: {}", seg.text);
            std::process::exit(1);
        }
        if seg.info == Some(true) {
            eprintln!("(soniox reconnecting)");
            continue;
        }
        let (Some(id), Some(s), Some(e)) = (seg.chunk_id.clone(), seg.start_ms, seg.end_ms) else { continue };
        if !chunks.contains_key(&id) && chunks.len() % 25 == 0 {
            // Soniox's own processing position: realtime STT lags a fast
            // feed, so this shows how far the server actually got.
            eprintln!("soniox at {:.0}s ({} chunks)", e as f64 / 1000.0, chunks.len());
        }
        chunks.insert(id, (s, e, seg.speaker_id));
    }
    let _ = feeder.await;
    let _ = session.await;

    let mut turns: Vec<(i64, i64, i64)> = chunks.into_values().filter(|(s, e, _)| e > s).collect();
    turns.sort_by_key(|t| t.0);
    let mut hist: BTreeMap<i64, i64> = BTreeMap::new();
    let mut lines = String::from("# start_s end_s speaker — generated by examples/soniox_labels.rs\n");
    for (s, e, spk) in &turns {
        *hist.entry(*spk).or_default() += e - s;
        lines.push_str(&format!("{:.3} {:.3} S{}\n", *s as f64 / 1000.0, *e as f64 / 1000.0, spk));
    }
    std::fs::write(out, lines).expect("write labels");
    println!("{} turns -> {out}", turns.len());
    for (spk, ms) in hist {
        println!("  S{spk}: {:.0}s", ms as f64 / 1000.0);
    }
}
